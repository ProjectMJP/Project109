using System;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace EventBinderGenerator
{
    [Generator]
    public class EventBinderSourceGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context)
        {
            // 특별한 초기화가 필요하지 않음
        }

        public void Execute(GeneratorExecutionContext context)
        {
            // Assembly-CSharp 어셈블리 컴파일 시에만 생성되도록 필터링
            if (context.Compilation.AssemblyName != "Assembly-CSharp")
                return;

            // 1. 모든 인터페이스 수집
            List<INamedTypeSymbol> interfaces = new List<INamedTypeSymbol>();
            CollectInterfaces(context.Compilation.GlobalNamespace, interfaces);

            List<INamedTypeSymbol> characterEventSymbols = new List<INamedTypeSymbol>();
            List<INamedTypeSymbol> playerEventSymbols = new List<INamedTypeSymbol>();

            // 2. 각 인터페이스 분류 (ICharacterEvent, IPlayerEvent 상속 기준)
            foreach (var iface in interfaces)
            {
                if (iface.Name == "ICharacterEvent" || iface.Name == "IPlayerEvent")
                    continue;

                if (InheritsFrom(iface, "ICharacterEvent"))
                {
                    characterEventSymbols.Add(iface);
                }
                else if (InheritsFrom(iface, "IPlayerEvent"))
                {
                    playerEventSymbols.Add(iface);
                }
            }

            // 이름순 정렬하여 결정론적 코드 생성 보장
            characterEventSymbols.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));
            playerEventSymbols.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));

            // 3. LuaEventBinder.g.cs 생성
            GenerateLuaEventBinder(context, characterEventSymbols, playerEventSymbols);

            // 4. CombatEventDispatcher.g.cs 및 PlayerEventDispatcher.g.cs 생성
            GenerateEventDispatcher(context, "CombatEventDispatcher", "ICharacterEvent", characterEventSymbols);
            GenerateEventDispatcher(context, "PlayerEventDispatcher", "IPlayerEvent", playerEventSymbols);
        }

        private void GenerateLuaEventBinder(
            GeneratorExecutionContext context,
            List<INamedTypeSymbol> characterEvents,
            List<INamedTypeSymbol> playerEvents)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using XLua;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("");
            sb.AppendLine("public static partial class LuaEventBinder");
            sb.AppendLine("{");

            // Character Events Binding Method
            sb.AppendLine("    public static partial void BindCharacterEvents(LuaTable luaTable, EventBus<ICharacterEvent> eventBus, List<object> activeProxies)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (luaTable == null || eventBus == null) return;");
            sb.AppendLine("");
            foreach (var iface in characterEvents)
            {
                string fqName = iface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string methodName = iface.Name.StartsWith("I") ? iface.Name.Substring(1) : iface.Name;
                sb.AppendLine($"        BindCharacter<{fqName}>(luaTable, \"{methodName}\", eventBus, activeProxies);");
            }
            sb.AppendLine("    }");
            sb.AppendLine("");

            // Character Events Unbinding Method
            sb.AppendLine("    public static partial void UnbindCharacterEvents(EventBus<ICharacterEvent> eventBus, List<object> activeProxies)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (eventBus == null || activeProxies == null) return;");
            sb.AppendLine("        foreach (var proxy in activeProxies)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (proxy == null) continue;");
            foreach (var iface in characterEvents)
            {
                string fqName = iface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string safeVar = fqName.Replace(".", "_").Replace(":", "_").Replace(" ", "_").Replace("<", "_").Replace(">", "_");
                sb.AppendLine($"            if (proxy is {fqName} p_{safeVar}) eventBus.Remove<{fqName}>(p_{safeVar});");
            }
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("");

            // Player Events Binding Method
            sb.AppendLine("    public static partial void BindPlayerEvents(LuaTable luaTable, EventBus<IPlayerEvent> eventBus, List<object> activeProxies)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (luaTable == null || eventBus == null) return;");
            sb.AppendLine("");
            foreach (var iface in playerEvents)
            {
                string fqName = iface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string methodName = iface.Name.StartsWith("I") ? iface.Name.Substring(1) : iface.Name;
                sb.AppendLine($"        BindPlayer<{fqName}>(luaTable, \"{methodName}\", eventBus, activeProxies);");
            }
            sb.AppendLine("    }");
            sb.AppendLine("");

            // Player Events Unbinding Method
            sb.AppendLine("    public static partial void UnbindPlayerEvents(EventBus<IPlayerEvent> eventBus, List<object> activeProxies)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (eventBus == null || activeProxies == null) return;");
            sb.AppendLine("        foreach (var proxy in activeProxies)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (proxy == null) continue;");
            foreach (var iface in playerEvents)
            {
                string fqName = iface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string safeVar = fqName.Replace(".", "_").Replace(":", "_").Replace(" ", "_").Replace("<", "_").Replace(">", "_");
                sb.AppendLine($"            if (proxy is {fqName} p_{safeVar}) eventBus.Remove<{fqName}>(p_{safeVar});");
            }
            sb.AppendLine("        }");
            sb.AppendLine("    }");

            sb.AppendLine("}");

            context.AddSource("LuaEventBinder.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private void GenerateEventDispatcher(
            GeneratorExecutionContext context,
            string dispatcherClassName,
            string baseEventInterfaceName,
            List<INamedTypeSymbol> eventInterfaces)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("");
            sb.AppendLine($"public static partial class {dispatcherClassName}");
            sb.AppendLine("{");

            foreach (var iface in eventInterfaces)
            {
                IMethodSymbol? targetMethod = null;
                foreach (var member in iface.GetMembers())
                {
                    if (member is IMethodSymbol method && method.MethodKind == MethodKind.Ordinary)
                    {
                        targetMethod = method;
                        break;
                    }
                }

                if (targetMethod == null)
                    continue;

                string fqInterfaceName = iface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string dispatchSuffix = iface.Name.StartsWith("IOn")
                    ? iface.Name.Substring(3)
                    : (iface.Name.StartsWith("I") ? iface.Name.Substring(1) : iface.Name);
                string dispatchMethodName = "Dispatch" + dispatchSuffix;

                StringBuilder paramDeclBuilder = new StringBuilder();
                StringBuilder argCallBuilder = new StringBuilder();

                for (int i = 0; i < targetMethod.Parameters.Length; i++)
                {
                    var param = targetMethod.Parameters[i];
                    string refPrefix = "";
                    if (param.RefKind == RefKind.Ref) refPrefix = "ref ";
                    else if (param.RefKind == RefKind.Out) refPrefix = "out ";
                    else if (param.RefKind == RefKind.In) refPrefix = "in ";

                    string paramType = param.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    paramDeclBuilder.Append($", {refPrefix}{paramType} {param.Name}");

                    if (i > 0) argCallBuilder.Append(", ");
                    argCallBuilder.Append($"{refPrefix}{param.Name}");
                }

                sb.AppendLine($"    public static void {dispatchMethodName}(EventBus<{baseEventInterfaceName}> bus{paramDeclBuilder})");
                sb.AppendLine("    {");
                sb.AppendLine($"        if (bus != null && bus.TryGetListeners<{fqInterfaceName}>(out var listeners))");
                sb.AppendLine("        {");
                sb.AppendLine("            for (int i = listeners.Count - 1; i >= 0; i--)");
                sb.AppendLine($"                listeners[i].{targetMethod.Name}({argCallBuilder});");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                sb.AppendLine("");
            }

            sb.AppendLine("}");

            context.AddSource($"{dispatcherClassName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private void CollectInterfaces(INamespaceSymbol ns, List<INamedTypeSymbol> result)
        {
            if (ns == null) return;

            foreach (var member in ns.GetMembers())
            {
                if (member is INamespaceSymbol nestedNs)
                {
                    CollectInterfaces(nestedNs, result);
                }
                else if (member is INamedTypeSymbol typeSymbol)
                {
                    CollectTypes(typeSymbol, result);
                }
            }
        }

        private void CollectTypes(INamedTypeSymbol type, List<INamedTypeSymbol> result)
        {
            if (type == null) return;

            if (type.TypeKind == TypeKind.Interface)
            {
                result.Add(type);
            }

            foreach (var nestedType in type.GetTypeMembers())
            {
                CollectTypes(nestedType, result);
            }
        }

        private bool InheritsFrom(INamedTypeSymbol symbol, string targetName)
        {
            if (symbol == null) return false;

            if (symbol.Name == targetName)
                return true;

            foreach (var iface in symbol.AllInterfaces)
            {
                if (iface.Name == targetName)
                    return true;
            }

            return false;
        }
    }
}
